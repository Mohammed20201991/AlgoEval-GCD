"""## 5. Primary analysis: regression  [R1-1] [R1-4]

Exactly four models: Linear Regression, Support Vector Regression, Random Forest, Neural
Network. Every model is scored with the **same** function (`evaluate_regressor`) on the
**same** Test set with the **same** three metrics (MAE, RMSE, R²), and plotted with the
**same** function (`plot_actual_vs_predicted`) -- no model gets a different kind of results
artifact.
"""

def build_nn_regressor(input_dim):
    from tensorflow import keras
    from tensorflow.keras import layers
    model = keras.Sequential([
        layers.Input(shape=(input_dim,)),
        layers.BatchNormalization(),
        layers.Dense(64, activation="relu"),
        layers.Dropout(0.2),
        layers.Dense(32, activation="relu"),
        layers.Dropout(0.1),
        layers.Dense(1, activation="linear"),
    ])
    model.compile(optimizer="adam", loss="mse", metrics=["mae"])
    return model


def evaluate_regressor(name, y_true, y_pred, results_list):
    mae = mean_absolute_error(y_true, y_pred)
    rmse = np.sqrt(mean_squared_error(y_true, y_pred))
    r2 = r2_score(y_true, y_pred)
    results_list.append({"Model": name, "MAE": mae, "RMSE": rmse, "R2": r2})
    print(f"[{name}]  MAE={mae:.4f}  RMSE={rmse:.4f}  R2={r2:.4f}  (Test set)")
    return mae, rmse, r2


def plot_actual_vs_predicted(y_true, y_pred, model_name, ax=None):
    own_fig = ax is None
    if own_fig:
        fig, ax = plt.subplots(figsize=(6, 6))
    ax.scatter(y_true, y_pred, alpha=0.4, s=10)
    lims = [min(y_true.min(), y_pred.min()), max(y_true.max(), y_pred.max())]
    ax.plot(lims, lims, "r--", label="Perfect prediction")
    ax.set_xlabel("Actual CPU usage (Test set)")
    ax.set_ylabel("Predicted CPU usage (Test set)")
    ax.set_title(model_name)
    ax.legend()
    ax.grid(True)
    if own_fig:
        plt.tight_layout()
        plt.show()

def run_regression_suite(X_train, X_val, X_test, y_train, y_val, y_test):
    scaler = StandardScaler()
    X_train_s = scaler.fit_transform(X_train)
    X_val_s = scaler.transform(X_val)
    X_test_s = scaler.transform(X_test)

    results = []
    predictions = {}

    # --- Linear Regression ---
    lr = LinearRegression()
    lr.fit(X_train_s, y_train)
    pred = lr.predict(X_test_s)
    evaluate_regressor("Linear Regression", y_test, pred, results)
    predictions["Linear Regression"] = pred

    # --- Support Vector Regression ---
    # SVR is O(n^2)-O(n^3); subsample for tractability and STATE the
    # subsample size explicitly in the paper.
    svr_sample_n = min(20000, len(X_train_s))
    idx = np.random.RandomState(RANDOM_STATE).choice(
        len(X_train_s), svr_sample_n, replace=False
    )
    svr = SVR(kernel="rbf", C=10, epsilon=0.01)
    svr.fit(X_train_s[idx], y_train.values[idx])
    pred = svr.predict(X_test_s)
    evaluate_regressor("Support Vector Regression", y_test, pred, results)
    predictions["Support Vector Regression"] = pred

    # --- Random Forest ---
    rf = RandomForestRegressor(
        n_estimators=200, max_depth=None, random_state=RANDOM_STATE, n_jobs=-1
    )
    rf.fit(X_train, y_train)
    pred = rf.predict(X_test)
    evaluate_regressor("Random Forest", y_test, pred, results)
    predictions["Random Forest"] = pred

    # --- Neural Network ---
    from tensorflow import keras
    nn = build_nn_regressor(X_train_s.shape[1])
    early_stop = keras.callbacks.EarlyStopping(
        monitor="val_loss", patience=8, restore_best_weights=True
    )
    nn.fit(
        X_train_s, y_train, validation_data=(X_val_s, y_val),
        epochs=100, batch_size=256, callbacks=[early_stop], verbose=0,
    )
    pred = nn.predict(X_test_s, verbose=0).flatten()
    evaluate_regressor("Neural Network", y_test, pred, results)
    predictions["Neural Network"] = pred

    # --- Hybrid model: simple average ensemble of the two best models ---
    results_df = pd.DataFrame(results).sort_values("RMSE")
    best_single_name = results_df.iloc[0]["Model"]
    second_best_name = results_df.iloc[1]["Model"]
    hybrid_pred = (predictions[best_single_name] + predictions[second_best_name]) / 2
    evaluate_regressor(
        f"Hybrid ({best_single_name} + {second_best_name})",
        y_test, hybrid_pred, results,
    )
    predictions["Hybrid"] = hybrid_pred

    results_df = pd.DataFrame(results).sort_values("RMSE").reset_index(drop=True)
    print("\n=== REGRESSION RESULTS -- all models, same Test set, same metrics ===")
    print(results_df.to_string(index=False))

    return results_df, predictions, best_single_name


reg_results, reg_predictions, best_single_name = run_regression_suite(
    X_train, X_val, X_test, y_train, y_val, y_test
)
