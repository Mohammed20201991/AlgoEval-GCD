import ast

FEATURE_GROUPS = {
    "dispatch_time": [
        "scheduling_class",      # known when task is submitted
        "priority",               # known at submission
        "resource_request_cpus",  # requested, not realized
        "resource_request_memory",
        "vertical_scaling",       # policy flag, known at submission
        "scheduler",              # which scheduler will place the task
        "collection_type",        # job/allocation type, known at submission
    ],
    # Everything below is only known AFTER the task has run. NONE of these
    # are used as model inputs -- this is what [R1-3] requires.
    "post_execution_do_not_use_as_features": [
        "start_time", "end_time", "assigned_memory", "page_cache_memory",
        "cycles_per_instruction", "memory_accesses_per_instruction",
        "average_usage_memory", "maximum_usage_cpus", "maximum_usage_memory",
        "random_sample_usage_cpus", "cpu_usage_distribution",
        "tail_cpu_usage_distribution", "failed",
    ],
}

DISPATCH_TIME_FEATURES = FEATURE_GROUPS["dispatch_time"]
TARGET_REGRESSION = "average_usage"


def build_feature_target_frame(df):
    """Selects dispatch-time features + regression target, drops missing rows, encodes cats."""
    needed = [c for c in DISPATCH_TIME_FEATURES if c in df.columns]
    missing = [c for c in DISPATCH_TIME_FEATURES if c not in df.columns]
    if missing:
        print(f"NOTE: these expected columns were not found and will be skipped: {missing}")
    if TARGET_REGRESSION not in df.columns:
        raise KeyError(
            f"Target column '{TARGET_REGRESSION}' not found. "
            f"Available columns: {list(df.columns)}"
        )

    sub = df[needed + [TARGET_REGRESSION]].copy()

    # Parse the string representation of the dictionary in the TARGET_REGRESSION column
    # and extract the 'cpus' value, converting it to a float.
    sub[TARGET_REGRESSION] = sub[TARGET_REGRESSION].apply(lambda x: ast.literal_eval(x)['cpus'] if pd.notna(x) and isinstance(x, str) else x)

    sub.dropna(inplace=True)

    cat_cols = sub[needed].select_dtypes(include="object").columns
    for c in cat_cols:
        sub[c] = sub[c].astype("category").cat.codes

    X = sub[needed]
    y = sub[TARGET_REGRESSION]
    return X, y


X, y = build_feature_target_frame(df_raw)
