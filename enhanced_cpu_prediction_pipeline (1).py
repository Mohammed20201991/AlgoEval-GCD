# 13. Custom weighted Huber loss for upper-tail awareness
# ============================================================

def make_tail_weighted_huber(alpha=1.0):

    huber = keras.losses.Huber(
        delta=1.0,
        reduction=keras.losses.Reduction.NONE
    )

    def loss(y_true, y_pred):

        base = huber(y_true, y_pred)

        # y_true here is log1p(target), so larger values receive
        # somewhat more importance without allowing extreme samples
        # to dominate training.
        normalized = tf.clip_by_value(
            y_true / 3.0,
            0.0,
            1.0
        )

        weights = 1.0 + alpha * normalized

        return tf.reduce_mean(
            weights * base
        )

    return loss

