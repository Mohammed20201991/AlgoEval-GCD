class GatedResidualBlock(layers.Layer):

    def __init__(
        self,
        units,
        dropout_rate=0.15,
        l2_reg=1e-5,
        **kwargs
    ):
        super().__init__(**kwargs)

        self.units = units
        self.dropout_rate = dropout_rate
        self.l2_reg = l2_reg

        self.norm = layers.LayerNormalization()

        self.value_dense = layers.Dense(
            units,
            activation="gelu",
            kernel_regularizer=keras.regularizers.l2(l2_reg)
        )

        self.gate_dense = layers.Dense(
            units,
            activation="sigmoid",
            kernel_regularizer=keras.regularizers.l2(l2_reg)
        )

        self.mix_dense = layers.Dense(
            units,
            activation="gelu",
            kernel_regularizer=keras.regularizers.l2(l2_reg)
        )

        self.dropout = layers.Dropout(dropout_rate)

        self.projection = None

    def build(self, input_shape):

        if input_shape[-1] != self.units:
            self.projection = layers.Dense(self.units)

        super().build(input_shape)

    def call(self, inputs, training=False):

        x = self.norm(inputs)

        value = self.value_dense(x)
        gate = self.gate_dense(x)

        gated = value * gate

        mixed = self.mix_dense(gated)

        mixed = self.dropout(
            mixed,
            training=training
        )

        if self.projection is not None:
            residual = self.projection(inputs)
        else:
            residual = inputs

        return residual + mixed


def build_dgrnn(
    input_dim,
    width=128,
    blocks=3,
    dropout=0.15,
    learning_rate=1e-3
):

    inputs = keras.Input(
        shape=(input_dim,),
        name="dispatch_features"
    )

    x = layers.Dense(
        width,
        activation="gelu"
    )(inputs)

    x = layers.LayerNormalization()(x)

    for _ in range(blocks):
        x = GatedResidualBlock(
            width,
            dropout_rate=dropout
        )(x)

    x = layers.Dense(
        width // 2,
        activation="gelu"
    )(x)

    x = layers.Dropout(dropout)(x)

    outputs = layers.Dense(
        1,
        activation="linear",
        name="cpu_usage"
    )(x)

    model = keras.Model(
        inputs,
        outputs,
        name="DGRNN"
    )

    model.compile(
        optimizer=keras.optimizers.AdamW(
            learning_rate=learning_rate,
            weight_decay=1e-5,
            clipnorm=1.0
        ),
        loss=keras.losses.Huber(delta=1.0),
        metrics=[
            keras.metrics.MeanAbsoluteError(name="mae")
        ]
    )

    return model

