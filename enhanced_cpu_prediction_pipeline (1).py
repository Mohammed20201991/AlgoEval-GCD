def parse_nested_value(value, key):
    """
    Handles:
      - Python dictionaries
      - stringified dictionaries
      - JSON-like strings
      - NaN/None
      - numeric values

    Example:
      "{'cpus': 0.05, 'memory': 1000000}"
    """

    if value is None:
        return np.nan

    if isinstance(value, float) and np.isnan(value):
        return np.nan

    if isinstance(value, dict):
        out = value.get(key, np.nan)
        try:
            return float(out)
        except Exception:
            return np.nan

    if isinstance(value, str):
        s = value.strip()

        if not s:
            return np.nan

        try:
            obj = ast.literal_eval(s)

            if isinstance(obj, dict):
                out = obj.get(key, np.nan)
                try:
                    return float(out)
                except Exception:
                    return np.nan

        except Exception:
            pass

        try:
            obj = json.loads(s)

            if isinstance(obj, dict):
                out = obj.get(key, np.nan)
                try:
                    return float(out)
                except Exception:
                    return np.nan

        except Exception:
            pass

    try:
        return float(value)
    except Exception:
        return np.nan


