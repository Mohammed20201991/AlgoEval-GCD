def parse_nested_value(value, key):
    """
    Extract a value such as 'cpus' or 'memory' from a nested
    dictionary stored as a string.

    Returns NaN if the field cannot be parsed.
    """
    if pd.isna(value):
        return np.nan

    if isinstance(value, dict):
        return value.get(key, np.nan)

    if not isinstance(value, str):
        return np.nan

    try:
        obj = ast.literal_eval(value)
        if isinstance(obj, dict):
            return obj.get(key, np.nan)
    except Exception:
        pass

    try:
        obj = json.loads(value)
        if isinstance(obj, dict):
            return obj.get(key, np.nan)
    except Exception:
        pass

    return np.nan


def build_feature_target_frame(df):
    """
    Build model features and target from the original Google Cluster
    dataset.

    The resource_request_cpus and resource_request_memory columns are
    derived from the nested resource_request field.
    """

    # ------------------------------------------------------------
    # Original columns that must exist in the dataset
    # ------------------------------------------------------------
    required_columns = [
        "scheduling_class",
        "priority",
        "resource_request",
        "vertical_scaling",
        "scheduler",
        "collection_type",
        "average_usage",
    ]

    missing = [
        c for c in required_columns
        if c not in df.columns
    ]

    if missing:
        raise KeyError(
            "Missing required original columns: "
            + ", ".join(missing)
        )

    # ------------------------------------------------------------
    # Start with the original dispatch-time fields
    # ------------------------------------------------------------
    sub = df[
        [
            "scheduling_class",
            "priority",
            "resource_request",
            "vertical_scaling",
            "scheduler",
            "collection_type",
            "average_usage",
        ]
    ].copy()

    # ------------------------------------------------------------
    # Extract CPU and memory from resource_request
    # ------------------------------------------------------------
    sub["resource_request_cpus"] = (
        sub["resource_request"]
        .apply(lambda x: parse_nested_value(x, "cpus"))
    )

    sub["resource_request_memory"] = (
        sub["resource_request"]
        .apply(lambda x: parse_nested_value(x, "memory"))
    )

    # ------------------------------------------------------------
    # Extract realized CPU usage from average_usage
    # ------------------------------------------------------------
    sub["realized_cpu_usage"] = (
        sub["average_usage"]
        .apply(lambda x: parse_nested_value(x, "cpus"))
    )

    # ------------------------------------------------------------
    # If parsing did not work because values are already numeric,
    # preserve numeric values.
    # ------------------------------------------------------------
    numeric_average_usage = pd.to_numeric(
        sub["average_usage"],
        errors="coerce"
    )

    sub["realized_cpu_usage"] = sub[
        "realized_cpu_usage"
    ].fillna(numeric_average_usage)

    # ------------------------------------------------------------
    # Final model features
    # ------------------------------------------------------------
    feature_columns = [
        "scheduling_class",
        "priority",
        "resource_request_cpus",
        "resource_request_memory",
        "vertical_scaling",
        "scheduler",
        "collection_type",
    ]

    target_column = "realized_cpu_usage"

    # Convert to numeric
    for col in feature_columns + [target_column]:
        sub[col] = pd.to_numeric(
            sub[col],
            errors="coerce"
        )

    # Replace infinite values
    sub = sub.replace(
        [np.inf, -np.inf],
        np.nan
    )

    # Remove rows with missing model features/target
    before = len(sub)

    sub = sub.dropna(
        subset=feature_columns + [target_column]
    ).copy()

    after = len(sub)

    print("=" * 70)
    print("FEATURE/TARGET PREPARATION")
    print("=" * 70)
    print(f"Rows before NA removal: {before:,}")
    print(f"Rows after NA removal:  {after:,}")
    print(f"Rows removed:          {before - after:,}")
    print("=" * 70)

    # ------------------------------------------------------------
    # Return X and y
    # ------------------------------------------------------------
    X = sub[feature_columns].copy()
    y = sub[target_column].astype(float).copy()

    return X, y


