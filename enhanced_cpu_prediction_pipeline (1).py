def engineer_dispatch_features(X):

    out = X.copy()

    # Log transforms for highly skewed resource quantities
    out["log_request_cpus"] = np.log1p(
        np.clip(out["resource_request_cpus"], 0, None)
    )

    out["log_request_memory"] = np.log1p(
        np.clip(out["resource_request_memory"], 0, None)
    )

    # CPU-memory interaction
    out["request_memory_per_cpu"] = (
        out["resource_request_memory"]
        / (out["resource_request_cpus"] + 1e-8)
    )

    out["log_memory_per_cpu"] = np.log1p(
        np.clip(out["request_memory_per_cpu"], 0, None)
    )

    # Dispatch-time interaction terms
    out["priority_x_cpu"] = (
        out["priority"] * out["resource_request_cpus"]
    )

    out["priority_x_memory"] = (
        out["priority"] * out["log_request_memory"]
    )

    out["class_x_cpu"] = (
        out["scheduling_class"] *
        out["resource_request_cpus"]
    )

    out["collection_x_cpu"] = (
        out["collection_type"] *
        out["resource_request_cpus"]
    )

    out["scheduler_x_cpu"] = (
        out["scheduler"] *
        out["resource_request_cpus"]
    )

    out["vertical_x_cpu"] = (
        out["vertical_scaling"] *
        out["resource_request_cpus"]
    )

    # Squared resource terms allow nonlinear response
    out["cpu_squared"] = (
        out["resource_request_cpus"] ** 2
    )

    out["log_memory_squared"] = (
        out["log_request_memory"] ** 2
    )

    out = out.replace([np.inf, -np.inf], np.nan)
    out = out.fillna(0.0)

    return out


