# 27. Classification metrics
# ============================================================

def classification_metrics(
    name,
    y_true,
    y_pred
):

    result = {
        "Model": name,
        "Accuracy": accuracy_score(
            y_true,
            y_pred
        ),
        "Precision": precision_score(
            y_true,
            y_pred,
            zero_division=0
        ),
        "Recall": recall_score(
            y_true,
            y_pred,
            zero_division=0
        ),
        "F1": f1_score(
            y_true,
            y_pred,
            zero_division=0
        )
    }

    print(
        f"[{name}] "
        f"Accuracy={result['Accuracy']:.6f} "
        f"Precision={result['Precision']:.6f} "
        f"Recall={result['Recall']:.6f} "
        f"F1={result['F1']:.6f}"
    )

    return result


