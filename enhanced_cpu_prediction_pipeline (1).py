def binary_focal_loss(
    gamma=2.0,
    alpha=0.75
):

    def loss(y_true, y_pred):

        y_true = tf.cast(
            y_true,
            tf.float32
        )

        y_pred = tf.clip_by_value(
            y_pred,
            1e-7,
            1.0 - 1e-7
        )

        pt = (
            y_true * y_pred
            + (1.0 - y_true)
            * (1.0 - y_pred)
        )

        alpha_t = (
            y_true * alpha
            + (1.0 - y_true)
            * (1.0 - alpha)
        )

        focal = (
            -alpha_t
            * tf.pow(
                1.0 - pt,
                gamma
            )
            * tf.math.log(pt)
        )

        return tf.reduce_mean(
            focal
        )

    return loss


